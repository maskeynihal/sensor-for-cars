#!/usr/bin/env python3
"""Convert the two boot images into boot_art.h (16-colour palette, 4-bit pixels).

Stdlib only. Steps (macOS sips does the resize and the PNG -> BMP step):

  cd projects/hj60_coolant
  sips -z 294 480 docs/img/design-boot-title.png --out /tmp/t.png && sips -s format bmp /tmp/t.png --out p1.bmp
  sips -z 240 480 docs/img/design-boot-truck.png --out /tmp/u.png && sips -s format bmp /tmp/u.png --out p2.bmp
  python3 tools/png_to_boot_art.py          # writes boot_art.h and p1_q.bmp / p2_q.bmp previews
  mv boot_art.h emulator/wokwi/hj60_coolant_sim/ && rm p1*.bmp p2*.bmp
"""
import struct, sys, collections, zlib

def read_bmp(path):
    d = open(path, 'rb').read()
    off = struct.unpack_from('<I', d, 10)[0]
    w, h = struct.unpack_from('<ii', d, 18)
    bpp = struct.unpack_from('<H', d, 28)[0]
    comp = struct.unpack_from('<I', d, 30)[0]
    assert bpp in (24, 32), bpp
    bypp = bpp // 8
    row = ((w * bypp + 3) // 4) * 4
    flip = h > 0
    h = abs(h)
    px = []
    for y in range(h):
        sy = h - 1 - y if flip else y
        base = off + sy * row
        for x in range(w):
            b, g, r = d[base + x*bypp], d[base + x*bypp + 1], d[base + x*bypp + 2]
            px.append((r, g, b))
    return w, h, px

def kmeans(px, k=16, it=8):
    cnt = collections.Counter((r >> 3, g >> 3, b >> 3) for r, g, b in px)
    # seed: most common buckets, spread apart
    seeds = []
    for c, _ in cnt.most_common():
        cc = (c[0]*8+4, c[1]*8+4, c[2]*8+4)
        if all(sum((a-b)**2 for a, b in zip(cc, s)) > 900 for s in seeds):
            seeds.append(cc)
        if len(seeds) == k: break
    cent = seeds
    sample = px[::3]
    for _ in range(it):
        acc = [[0, 0, 0, 0] for _ in cent]
        for p in sample:
            bi = min(range(len(cent)), key=lambda i: (p[0]-cent[i][0])**2 + (p[1]-cent[i][1])**2 + (p[2]-cent[i][2])**2)
            a = acc[bi]; a[0] += p[0]; a[1] += p[1]; a[2] += p[2]; a[3] += 1
        cent = [(a[0]//a[3], a[1]//a[3], a[2]//a[3]) if a[3] else cent[i] for i, a in enumerate(acc)]
    return cent

def quant(px, cent):
    cache = {}
    out = []
    for p in px:
        if p not in cache:
            cache[p] = min(range(len(cent)), key=lambda i: (p[0]-cent[i][0])**2 + (p[1]-cent[i][1])**2 + (p[2]-cent[i][2])**2)
        out.append(cache[p])
    return out

def write_bmp(path, w, h, idx, cent):
    row = ((w*3+3)//4)*4
    data = bytearray()
    for y in range(h-1, -1, -1):
        r = bytearray()
        for x in range(w):
            c = cent[idx[y*w+x]]; r += bytes((c[2], c[1], c[0]))
        r += b'\0' * (row - len(r)); data += r
    hdr = b'BM' + struct.pack('<IHHI', 54+len(data), 0, 0, 54) + struct.pack('<IiiHHIIiiII', 40, w, h, 1, 24, 0, len(data), 2835, 2835, 0, 0)
    open(path, 'wb').write(hdr + data)

out = ['// Generated by tools/png_to_boot_art.py from docs/img/design-boot-*.png.',
       '// 16-colour palette (RGB565) + 4-bit pixels, two pixels per byte (high nibble first).',
       '// Do not edit by hand.', '#pragma once', '#include <stdint.h>', '']
for name, path in (('BOOT_TITLE', 'p1.bmp'), ('BOOT_TRUCK', 'p2.bmp')):
    w, h, px = read_bmp(path)
    cent = kmeans(px)
    while len(cent) < 16: cent.append((0, 0, 0))
    # darkest colour first, so index 0 is the background
    order = sorted(range(16), key=lambda i: sum(cent[i]))
    cent = [cent[i] for i in order]
    idx = quant(px, cent)
    write_bmp(path.replace('.bmp', '_q.bmp'), w, h, idx, cent)
    pal = [((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3) for r, g, b in cent]
    packed = bytearray()
    for i in range(0, len(idx), 2):
        packed.append((idx[i] << 4) | (idx[i+1] if i+1 < len(idx) else 0))
    out.append(f'const uint16_t {name}_W = {w}, {name}_H = {h};')
    out.append(f'const uint16_t {name}_PAL[16] = {{' + ', '.join(f'0x{c:04X}' for c in pal) + '};')
    out.append(f'const uint8_t {name}_PIX[{len(packed)}] = {{')
    for i in range(0, len(packed), 24):
        out.append('  ' + ', '.join(f'0x{b:02X}' for b in packed[i:i+24]) + ',')
    out.append('};')
    out.append('')
    print(name, w, h, len(packed), 'bytes')
open('boot_art.h', 'w').write('\n'.join(out))
